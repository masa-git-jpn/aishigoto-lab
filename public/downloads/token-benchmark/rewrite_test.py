#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
書き方を変えるとトークン数はどれだけ減るのか。

**意味を変えずに**表記だけを変えた組を用意して、前後のトークン数を比べる。
プロンプトを短くしたい人が実際に使える形にするのが目的。

「意味が同じ」はこちらの判断なので、全ペアを記事とデータに全文載せて、
読者が自分で見て判断できるようにしている。

出力: results_rewrite.json
"""
import json

from tokenizers_setup import ORDER, load_all

# (施策名, 変更前, 変更後, 意味が変わっていないかの注記)
PAIRS = [
    (
        "全角英数を半角にする",
        "型番ＳＫＵ－２０２４－Ａ１００を２０個、単価１，２５０円で発注してください。",
        "型番SKU-2024-A100を20個、単価1,250円で発注してください。",
        "表記のみ。数値・型番は同一",
    ),
    (
        "全角スペースのインデントをやめる",
        "・議題1　先月の受注実績について\n　　- 達成率は九割二分\n　　- 大口案件が翌月へずれ込んだ",
        "- 議題1 先月の受注実績について\n  - 達成率は九割二分\n  - 大口案件が翌月へずれ込んだ",
        "箇条書きの記号と字下げのみ変更",
    ),
    (
        "クッション言葉と定型の挨拶を削る",
        "お世話になっております。大変恐れ入りますが、先日ご相談させていただきました件につきまして、"
        "もしよろしければ、ご確認のうえご回答いただけますと大変幸いに存じます。",
        "先日ご相談した件について、確認して回答してください。",
        "依頼内容は同じ。敬語と前置きを削除",
    ),
    (
        "漢数字をアラビア数字にする",
        "第五条 契約期間は二十四箇月とし、違約金は残存期間の三十パーセントとする。",
        "第5条 契約期間は24箇月とし、違約金は残存期間の30%とする。",
        "数値は同一",
    ),
    (
        "表を罫線からCSVにする",
        "｜商品コード　｜数量　｜単価　｜\n｜4901234567890｜320　｜480　｜\n｜4901234567906｜85　　｜1250 ｜",
        "商品コード,数量,単価\n4901234567890,320,480\n4901234567906,85,1250",
        "含まれる値は同一",
    ),
    (
        "カタカナ語を漢語にする",
        "スケジュールのアップデートとリソースのアサインについてレビューを実施します。",
        "日程の更新と要員の割当について検討します。",
        "指す内容は同じ。語彙を変更",
    ),
    (
        "丁寧語をやめて体言止めにする",
        "本システムは、受信した注文データを検証したうえで在庫管理システムへ連携する構成となっています。"
        "処理は毎時零分に起動します。",
        "本システムは注文データを検証後、在庫管理システムへ連携。処理は毎時0分に起動。",
        "動作の説明は同一",
    ),
    (
        "繰り返す長い固有名詞を短縮して定義する",
        "株式会社サンプル商事の担当者は、株式会社サンプル商事の規程に従い、"
        "株式会社サンプル商事の様式で申請する。",
        "株式会社サンプル商事（以下A社）の担当者は、A社の規程に従い、A社の様式で申請する。",
        "指す対象は同一",
    ),
]


if __name__ == "__main__":
    tk = load_all()
    rows = []
    for name, before, after, note in PAIRS:
        rec = {"name": name, "before": before, "after": after, "note": note,
               "chars": {"before": len(before), "after": len(after)}, "tokens": {}}
        for n in ORDER:
            b = len(tk[n].encode(before))
            a = len(tk[n].encode(after))
            rec["tokens"][n] = {"before": b, "after": a, "delta": a - b,
                                "cut_pct": round((b - a) / b * 100, 1)}
        rows.append(rec)

    with open("results_rewrite.json", "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)

    print(f"{'施策':34s}{'文字数':>12}" +
          "".join(f"{n.replace('_base',''):>18}" for n in ["o200k_base", "cl100k_base", "gemma"]))
    print("-" * 100)
    for r in rows:
        c = f"{r['chars']['before']}→{r['chars']['after']}"
        line = f"{r['name']:34s}{c:>12}"
        for n in ["o200k_base", "cl100k_base", "gemma"]:
            t = r["tokens"][n]
            line += f"{t['before']:>7}→{t['after']:<4}{t['cut_pct']:>5.0f}%"
        print(line)

    # 全体の削減率（施策をまとめて適用したわけではなく、各ペアの合計）
    print("-" * 100)
    for n in ["o200k_base", "cl100k_base", "gemma"]:
        b = sum(r["tokens"][n]["before"] for r in rows)
        a = sum(r["tokens"][n]["after"] for r in rows)
        print(f"  {n:14s} 合計 {b} → {a} トークン（{(b-a)/b*100:.1f}% 削減）")
    print("\n保存: results_rewrite.json")
